# ──────────────────────────────────────────────
# DeepEval Quality Evaluation
# ──────────────────────────────────────────────

def run_deepeval_quality_evaluation(test_cases: list) -> dict:
    """Run DeepEval quality evaluation on the given test cases."""
    results = {}

    for case in test_cases:
        name = case["name"]
        query = case["query"]

        print(f"\nRunning DeepEval for: {name}")
        print(f"Query: {query}")

        # Get evaluation data from workflow
        eval_data = asyncio.run(get_evaluation_data(query))

        # Create DeepEval test case
        deepeval_case = LLMTestCase(
            input=query,
            actual_output=eval_data["answer"],
            retrieval_context=eval_data["contexts"],
        )

        # Initialize metrics
        metrics = [
            AnswerRelevancyMetric(),
            FaithfulnessMetric(),
            ContextualRelevancyMetric(),
        ]

        # Run each metric and collect scores
        metric_scores = {}
        for metric in metrics:
            try:
                score = metric.measure(deepeval_case)
                metric_scores[metric.name] = score
                print(f"  {metric.name}: {score:.2f}")
            except Exception as e:
                print(f"  {metric.name}: ERROR - {type(e).__name__}: {e}")
                metric_scores[metric.name] = 0.0

        results[name] = {
            "answer": eval_data["answer"],
            "contexts": eval_data["contexts"],
            "metric_scores": metric_scores,
        }

    return results


