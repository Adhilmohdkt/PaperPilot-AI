async def run_workflow_for_eval(query: str, conversation_id: str = "eval-test") -> dict:
    """Run the compiled LangGraph workflow and return the final state."""
    initial_state = {
        "conversation_id": conversation_id,
        "user_query": query,
        "messages": [],
        "intent": "general_answer",
        "response": "",
    }

    final_state = None
    async for chunk in workflow.astream(initial_state, config={"configurable": {"thread_id": conversation_id}}):
        final_state = chunk

    if final_state is None:
        final_state = await workflow.ainvoke(initial_state, config={"configurable": {"thread_id": conversation_id}})

    return final_state


async def get_evaluation_data(query: str) -> dict:
    """Run workflow and extract data needed for DeepEval evaluation."""
    state = await run_workflow_for_eval(query)

    answer = state.get("response", "") or ""

    # Extract context from ranked papers and academic papers
    contexts = []
    ranked_papers = state.get("ranked_papers", [])
    for paper in ranked_papers[:3]:  # Top 3 ranked papers
        ctx = paper.title or ""
        if paper.abstract:
            ctx += ". " + str(paper.abstract)[:200]
        contexts.append(ctx)

    # Get citations from citation validation
    citations = state.get("citations", [])

    return {
        "answer": answer,
        "contexts": contexts,
        "citations": citations,
    }


