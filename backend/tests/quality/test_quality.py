# ──────────────────────────────────────────────

def run_citation_evaluation(test_cases: list) -> dict:
    """Run deterministic citation evaluation checks."""
    results = {}

    for case in test_cases:
        name = case["name"]
        query = case["query"]

        print(f"\nRunning citation evaluation for: {name}")

        # Run workflow to get state
        state = asyncio.run(get_evaluation_data(query))

        answer = state["answer"]
        citations = state["citations"]

        # Deterministic citation checks
        citation_results = {
            "total_citations_in_answer": len(re.findall(r"\[Paper \d+\]", answer))
                              + len(re.findall(r"\[Source \d+\]", answer)),
            "citations_validated": sum(1 for c in citations if c.get("valid", False)),
            "citations_total": len(citations),
            "all_citations_have_source": all(
                c.get("details", "").find("exists in context") >= 0
                or c.get("valid", False)
                for c in citations
            ),
        }

        results[name] = {
            "answer": answer,
            "citations": citations,
            "citation_results": citation_results,
        }

    return results